export const SAARC_COUNTRY_CODES = ['AF', 'BD', 'BT', 'IN', 'MV', 'NP', 'PK'];
export const LOCAL_COUNTRY_CODE = 'LK';

export const isSaarcCountry = (code) => SAARC_COUNTRY_CODES.includes(code?.toUpperCase());
export const isLocalCountry = (code) => code?.toUpperCase() === LOCAL_COUNTRY_CODE;

export const getVisitorTypeByCountry = (code) => {
  if (isLocalCountry(code)) return 'local';
  if (isSaarcCountry(code)) return 'saarc';
  return 'foreign';
};

export const getCountryFlagUrl = (code) => {
  if (!code) return '';
  return `https://flagcdn.com/w40/${code.toLowerCase()}.png`;
};

export const getCountryFlagEmoji = (code) => {
  if (!code || code.length !== 2) return '🌐';
  const codePoints = code
    .toUpperCase()
    .split('')
    .map(char => 127397 + char.charCodeAt(0));
  return String.fromCodePoint(...codePoints);
};

export const getCountryClassification = (code) => {
  if (isLocalCountry(code)) {
    return {
      type: 'local',
      label: 'Local Resident',
      badge: 'Local',
      desc: 'Sri Lankan Resident (LKR 250)',
      rateUsd: 0,
      rateLkr: 250
    };
  }
  if (isSaarcCountry(code)) {
    return {
      type: 'saarc',
      label: 'SAARC Member Country',
      badge: 'SAARC',
      desc: 'SAARC Regional Discount Rate (USD ~30)',
      rateUsd: 30,
      rateLkr: 9300
    };
  }
  return {
    type: 'foreign',
    label: 'Non-SAARC Country',
    badge: 'Non-SAARC',
    desc: 'Standard International Rate (USD ~45)',
    rateUsd: 45,
    rateLkr: 14000
  };
};

